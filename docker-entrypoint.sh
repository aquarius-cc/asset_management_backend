#!/bin/bash
# =============================================================================
# Docker 入口脚本 - 数据库迁移和服务启动
# =============================================================================
set -uo pipefail

echo "============================================"
echo " 资产管理系统 Docker 启动脚本"
echo "============================================"

# =============================================================================
# 等待数据库就绪
# =============================================================================
echo "[1/4] 等待数据库连接..."

# 数据库连接参数（从环境变量读取）
DB_HOST=${DB_HOST:-postgres}
DB_PORT=${DB_PORT:-5432}
DB_NAME=${DB_NAME:-asset_management_backend}
DB_USER=${DB_USER:-postgres}
DB_PASSWORD=${DB_PASSWORD:-}

# 等待函数
wait_for_db() {
    echo "等待 PostgreSQL 就绪 ($DB_HOST:$DB_PORT)..."
    # 最多等待 60 秒
    timeout=60
    count=0
    while ! python -c "
import os, psycopg
conn = psycopg.connect(
    host=os.environ['DB_HOST'],
    port=int(os.environ['DB_PORT']),
    user=os.environ['DB_USER'],
    password=os.environ['DB_PASSWORD'],
    dbname=os.environ['DB_NAME'],
)
conn.close()
" 2>/dev/null; do
        count=$((count + 1))
        if [ $count -gt $timeout ]; then
            echo "错误：数据库连接超时"
            exit 1
        fi
        echo "  等待中... ($count/$timeout)"
        sleep 1
    done
    echo "数据库已就绪"
}

# 执行等待
wait_for_db

# =============================================================================
# 数据库迁移
# =============================================================================
echo "[2/4] 执行数据库迁移..."

cd /app
python manage.py migrate --noinput

# =============================================================================
# 收集静态文件
# =============================================================================
echo "[3/4] 收集静态文件..."

python manage.py collectstatic --noinput --clear

# =============================================================================
# 创建超级管理员（如果环境变量设置了）
# =============================================================================
echo "[4/4] 检查超级管理员..."

if [ -n "$DJANGO_SUPERUSER_USERNAME" ] && [ -n "$DJANGO_SUPERUSER_PASSWORD" ]; then
    echo "创建超级管理员..."
    python manage.py createsuperuser --noinput || true
else
    echo "! [警告] 未设置 DJANGO_SUPERUSER_USERNAME/PASSWORD，跳过超管创建——请部署后手动创建（或设置环境变量后重启容器）"
fi

# =============================================================================
# 初始化生产环境基础数据（RBAC 角色/权限/关联）
# =============================================================================
echo "[额外] 初始化 RBAC 基础数据..."
python manage.py init_production_data --skip-admin 2>&1 || exit 1

# =============================================================================
# 启动应用
# =============================================================================
echo "============================================"
echo " 启动应用..."
echo "============================================"
exec "$@"
